"""Exact root-of-unity q-Pascal factorization, research oracle not fast FFT.

All vector outputs are materialized; immutable preparation is charged separately.
The input consists of a field, N, and a primitive Nth root q. The field's root
finding and exact field representation costs are not unit arithmetic costs.
"""
from collections import Counter
from dataclasses import dataclass


class Counted:
    def __init__(self, field):
        self.field, self.count = field, Counter()
    def __getattr__(self, name):
        return getattr(self.field, name)
    def add(self, a, b):
        self.count['add'] += 1
        return self.field.add(a, b)
    def sub(self, a, b):
        self.count['sub'] += 1
        return self.field.sub(a, b)
    def mul(self, a, b):
        self.count['mul'] += 1
        return self.field.mul(a, b)
    def neg(self, a):
        self.count['neg'] += 1
        return self.field.neg(a)
    def inv(self, a):
        self.count['constant_inverse'] += 1
        return self.field.inv(a)


@dataclass
class Plan:
    n: int
    q: object
    factorial: list
    kernel: list
    middle: list
    preparation: dict


def prepare(field, n, q):
    """O(N) scalar preparation; no factorial inversions or lookup table.

One inversion obtains the constant 1/2. In a model supplying 1/2 this is
omitted. The power-of-two rational 1/N is then generated by log2(N) multiplies.
No input-dependent division occurs. Primitive-root validity is a precondition.
"""
    if n < 2 or n & (n-1):
        raise ValueError('N must be a power of two at least 2')
    c = Counted(field)
    powers = [field.one]
    for _ in range(1, n):
        powers.append(c.mul(powers[-1], q))
    factors = [field.one] + [c.sub(field.one, powers[j]) for j in range(1, n)]
    f = [field.one]
    for j in range(1, n):
        f.append(c.mul(f[-1], factors[j]))
    half = c.inv(field.integer(2))
    inverse_n = field.one
    for _ in range(n.bit_length()-1):
        inverse_n = c.mul(inverse_n, half)
    suffix, t = field.one, [field.zero] * n
    for j in reversed(range(n)):
        t[j] = c.mul(suffix, inverse_n)
        if j:
            suffix = c.mul(suffix, factors[j])
    chirp, middle = field.one, []
    for j in range(n):
        middle.append(c.mul(chirp, t[j]))
        if j+1 < n:
            chirp = c.neg(c.mul(chirp, powers[j]))
    return Plan(n, q, f, t, middle, dict(c.count))


def lower_convolution(field, kernel, x, traffic=None):
    """Direct truncated convolution: quadratic, deliberately not hidden FFT."""
    out = []
    for i in range(len(x)):
        value = field.mul(kernel[i], x[0])
        for j in range(1, i+1):
            value = field.add(value, field.mul(kernel[i-j], x[j]))
        out.append(value)
    if traffic is not None:
        n = len(x)
        traffic['kernel_reads'] += n*(n+1)//2
        traffic['input_reads'] += n*(n+1)//2
        traffic['convolution_output_writes'] += n
    return out


def apply(field, plan, x):
    """Return F_N x and charged direct-evaluator counts.

F = S T diag(d) T^T S. The same kernel applies T and T^T via reversal.
"""
    n = plan.n
    if len(x) != n:
        raise ValueError('wrong input length')
    c, traffic = Counted(field), Counter()
    v = [c.mul(a, b) for a, b in zip(plan.factorial, x)]
    v = list(reversed(lower_convolution(c, plan.kernel, list(reversed(v)), traffic)))
    v = [c.mul(a, b) for a, b in zip(plan.middle, v)]
    v = lower_convolution(c, plan.kernel, v, traffic)
    v = [c.mul(a, b) for a, b in zip(plan.factorial, v)]
    traffic['reversal_element_copies'] = 2*n
    traffic['diagonal_operand_reads'] = 6*n
    traffic['diagonal_output_writes'] = 3*n
    return v, {'field_operations': dict(c.count), 'array_traffic': dict(traffic)}


def hankel(field, plan, r, shift=0):
    if shift < 0 or shift+2*r-2 >= plan.n:
        raise ValueError('kernel indices outside available coefficients')
    return [[plan.kernel[shift+i+j] for j in range(r)] for i in range(r)]


def hankel_determinant_formula(field, plan, r, shift=0):
    """All nonzero for shift+2r-2 < N; proof in README.

det[t_(shift+i+j)] = q^(sum_{s=1}^{r-1} s^2)
  * product_(i<j)(q^(shift+j)-q^(shift+i))
  / product_i f_(shift+i+r-1).
"""
    if shift < 0 or shift+2*r-2 >= plan.n:
        raise ValueError('kernel indices outside available coefficients')
    out = field.power(plan.q, sum(s*s for s in range(1, r)))
    points = [field.power(plan.q, shift+i) for i in range(r)]
    for i in range(r):
        for j in range(i+1, r):
            out = field.mul(out, field.sub(points[j], points[i]))
        out = field.mul(out, plan.kernel[shift+i+r-1])
    return out
