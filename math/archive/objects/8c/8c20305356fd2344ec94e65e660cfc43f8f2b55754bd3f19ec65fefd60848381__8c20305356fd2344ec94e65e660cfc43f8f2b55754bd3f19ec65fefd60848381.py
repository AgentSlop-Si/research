"""Hero #17 Phase 7: exact Fourier rank-one rectangle tiles.

Model: one-pass disjoint rank-one rectangular blocks, each independently
contracted without cross-tile common-subexpression reuse. No claim about
unrestricted arithmetic-circuit lower bounds or novel FFT asymptotics.

A primitive Nth root of unity in F_p is supplied. All modular DFT outputs
are exact, all root table work and field operations in executors are counted.
"""
from __future__ import annotations
from dataclasses import dataclass
from math import gcd, isqrt
from typing import Sequence


def divisors(n: int) -> list[int]:
    if n <= 0:
        raise ValueError('n must be positive')
    dset = set()
    for k in range(1, isqrt(n) + 1):
        if n % k == 0:
            dset.update((k, n // k))
    return sorted(dset)


def optimal_divisor(n: int) -> int:
    """Subgroup order yielding minimum endpoint incidence."""
    return min(divisors(n), key=lambda d: (d + n // d, d))


def optimal_tile_cost(n: int) -> int:
    d = optimal_divisor(n)
    return n * (d + n // d)


def row_subgroup_order(rows: Sequence[int], n: int) -> int:
    """Size of subgroup generated by differences of listed row indices."""
    if not rows:
        raise ValueError('empty row set')
    base = rows[0] % n
    step = n
    for r in rows[1:]:
        step = gcd(step, (r - base) % n)
    return n // step


def rank_one_rectangle(rows: Sequence[int], cols: Sequence[int], n: int) -> bool:
    if not rows or not cols:
        return False
    if len(set(rows)) != len(rows) or len(set(cols)) != len(cols):
        raise ValueError('indices must be distinct')
    if any(not 0 <= r < n for r in rows) or any(not 0 <= c < n for c in cols):
        raise ValueError('indices outside 0..n-1')
    k0, j0 = rows[0], cols[0]
    return all(((k-k0)*(j-j0)) % n == 0 for k in rows for j in cols)


def rectangle_envelope(rows: Sequence[int], cols: Sequence[int], n: int) -> dict:
    """Return the maximal coset rectangle forced by the row-difference group.

    For any rank-one block R x C, R subset (k0+H), C subset(j0+H^perp),
    with |H|=d, |H^perp|=n/d, and |R||C|<=n.
    """
    if not rank_one_rectangle(rows, cols, n):
        raise ValueError('not a rank-one Fourier rectangle')
    d = row_subgroup_order(rows, n)
    q = n // d
    return {'row_coset': [(rows[0] + q * j) % n for j in range(d)],
            'col_coset': [(cols[0] + d * j) % n for j in range(q)],
            'row_capacity': d, 'col_capacity': q,
            'area': len(rows)*len(cols), 'max_area': n}


def subgroup_tiles(n: int, d: int | None = None) -> list[tuple[tuple[int, ...], tuple[int, ...]]]:
    if d is None:
        d = optimal_divisor(n)
    if d not in divisors(n):
        raise ValueError('d must divide n')
    q = n // d
    return [(tuple(r + q*v for v in range(d)),
             tuple(c + d*w for w in range(q)))
            for r in range(q) for c in range(d)]


def verify_partition(n: int, tiles: Sequence[tuple[Sequence[int], Sequence[int]]]) -> None:
    hit = [0]*(n*n)
    for rows, cols in tiles:
        assert rank_one_rectangle(rows, cols, n)
        for k in rows:
            for j in cols:
                hit[k*n+j] += 1
    assert all(x == 1 for x in hit), 'not an exact disjoint rectangle tiling'


def tile_cost(tiles: Sequence[tuple[Sequence[int], Sequence[int]]]) -> int:
    return sum(len(rows)+len(cols) for rows, cols in tiles)


def is_prime(k: int) -> bool:
    if k < 2:
        return False
    for d in range(2, isqrt(k)+1):
        if k%d == 0:
            return False
    return True


def prime_factors(k: int) -> set[int]:
    ans = set()
    d = 2
    while d*d <= k:
        if k%d == 0:
            ans.add(d)
            while k%d == 0:
                k //= d
        d += 1
    if k>1: ans.add(k)
    return ans


def test_field(n: int) -> tuple[int, int]:
    """Find prime p and supplied primitive n-th root w for test fixtures.

    Field discovery is an offline fixture step, NOT part of fast executor.
    """
    pf = prime_factors(n)
    for m in range(1,5000):
        p = m*n+1
        if not is_prime(p):
            continue
        for g in range(2,p):
            w = pow(g,(p-1)//n,p)
            if all(pow(w,n//q,p)!=1 for q in pf):
                return p,w
    raise RuntimeError('no test fixture field')


@dataclass
class Ledger:
    root_muls: int = 0
    muls: int = 0
    adds: int = 0
    output_writes: int = 0
    input_read_occurrences: int = 0
    butterflies: int = 0

    def as_dict(self) -> dict:
        return dict(self.__dict__)


def roots_table(n: int, w: int, p: int) -> tuple[list[int], int]:
    roots=[1]*n
    for i in range(1,n):
        roots[i]=(roots[i-1]*w)%p
    return roots,n-1


def direct_dft(x: Sequence[int], p: int, w: int) -> list[int]:
    n=len(x)
    roots,_=roots_table(n,w,p)
    return [sum(x[j]*roots[(-k*j)%n] for j in range(n))%p for k in range(n)]


def one_pass_tiled_dft(x: Sequence[int], p: int, w: int, d: int | None = None) -> tuple[list[int], Ledger]:
    """Exact direct contraction of N independent rank-one subgroup tiles.

    Per tile, q input products + (q-1) adds build a scalar, followed by
    d output products+adds. No power calls inside loops; all root lookup
    preparation is included in ledger.
    """
    n=len(x)
    if d is None: d=optimal_divisor(n)
    if n%d: raise ValueError('d must divide n')
    q=n//d
    powers, prep=roots_table(n,w,p)
    ledger=Ledger(root_muls=prep)
    output=[0]*n
    for r in range(q):
        for c in range(d):
            acc=0
            for j in range(q):
                in_index=c+d*j
                v=(x[in_index]*powers[(-r*d*j)%n])%p
                ledger.muls+=1;ledger.input_read_occurrences+=1
                if j: ledger.adds+=1
                acc=(acc+v)%p
            for v in range(d):
                out_index=r+q*v
                e=(-r*c-q*v*c)%n
                contribution=acc*powers[e]%p
                output[out_index]=(output[out_index]+contribution)%p
                ledger.muls+=1;ledger.adds+=1
    ledger.output_writes=n
    return output,ledger


def radix2_fft(a: Sequence[int], powers: Sequence[int], p:int) -> tuple[list[int], int]:
    """Standard radix-2 scalar circuit, counted butterflies, n | len(powers)."""
    n=len(a)
    N=len(powers)
    if n<=0 or (n&(n-1)) or N%n:
        raise ValueError('power-of-2 length divisor required')
    if n==1:
        return [a[0]%p],0
    ev,be=radix2_fft(a[0::2],powers,p)
    od,bo=radix2_fft(a[1::2],powers,p)
    out=[0]*n
    for k in range(n//2):
        tw=od[k]*powers[(-k*N//n)%N]%p
        out[k]=(ev[k]+tw)%p
        out[k+n//2]=(ev[k]-tw)%p
    return out,be+bo+n//2


def shared_two_axis_dft(x: Sequence[int],p:int,w:int,d:int|None=None) -> tuple[list[int], Ledger]:
    """Charge both short Fourier families: classical CT, not new faster FFT."""
    n=len(x)
    if d is None:d=optimal_divisor(n)
    q=n//d
    if d<=0 or n%d or (d&(d-1)) or (q&(q-1)):
        raise ValueError('d and n/d must be powers of two')
    powers,prep=roots_table(n,w,p)
    ledger=Ledger(root_muls=prep)
    S=[]
    for c in range(d):
        a,b=radix2_fft([x[c+d*j] for j in range(q)],powers,p)
        S.append(a)
        ledger.butterflies+=b
        ledger.input_read_occurrences+=q
    out=[0]*n
    for r in range(q):
        vals=[]
        for c in range(d):
            vals.append(S[c][r]*powers[(-r*c)%n]%p)
            ledger.muls+=1
        row,b=radix2_fft(vals,powers,p)
        ledger.butterflies+=b
        for v in range(d):
            out[r+q*v]=row[v]
    ledger.muls+=ledger.butterflies
    ledger.adds+=2*ledger.butterflies
    ledger.output_writes=n
    return out,ledger


def enumerate_rankone_tiles(n:int)->list[tuple[tuple[int,...],tuple[int,...],int,int]]:
    """Full subset enumeration for small n; independent small-instance MILP."""
    if n>8:raise ValueError('small-instance exhaustive checker only')
    subsets=[tuple(j for j in range(n) if mask & (1<<j))
             for mask in range(1,1<<n)]
    return [(I,J,len(I)+len(J),sum(1<<(r*n+c) for r in I for c in J))
            for I in subsets for J in subsets if rank_one_rectangle(I,J,n)]
