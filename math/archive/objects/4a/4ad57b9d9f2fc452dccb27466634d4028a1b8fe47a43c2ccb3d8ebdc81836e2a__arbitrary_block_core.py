#!/usr/bin/env python3
"""Arbitrary-length unequal-block unit-step-chirp Green evaluator (v14).

For any N and any balanced contiguous partition into B >= 3 blocks, one
random block-rank-one projected signal can be transformed *exactly* (for that
projected signal) without an N-point FFT.

The two forcing vectors are B-exponential sequences.  They are generated by
an order-B constant-coefficient recurrence, evaluated in blocks using
polynomial convolution / power-series division.  In an exact arithmetic model
this costs

    O(N + (N/B) M(B) + B^2)

where M(B) is polynomial multiplication cost.  With FFT multiplication this
is O(N log B + B^2).

The NumPy implementation is a reproducible algebraic prototype, not a
floating-point stability theorem.  High-order recurrences with unit-circle
roots can be ill-conditioned in binary64; exact finite-field certificates are
provided separately.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Iterable
import math
import numpy as np
import numpy.typing as npt

ComplexArray = npt.NDArray[np.complex128]


@dataclass(frozen=True)
class ChirpState:
    a: int
    beta: int

    def validate(self, n: int) -> None:
        if not (0 < self.a < n) or math.gcd(self.a, n) != 1:
            raise ValueError("a must be a unit modulo n")
        if not (0 <= self.beta < n):
            raise ValueError("beta must lie in [0,n)")


def draw_state(n: int, rng: np.random.Generator) -> ChirpState:
    if n < 2:
        raise ValueError("n must be at least two")
    cap = max(64, 8 * math.ceil(math.log2(n)) ** 2)
    for _ in range(cap):
        a = int(rng.integers(1, n))
        if math.gcd(a, n) == 1:
            return ChirpState(a, int(rng.integers(n)))
    raise RuntimeError("unit sampling budget exhausted")


def balanced_partition(n: int, blocks: int) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Return contiguous starts, lengths and ends for exactly ``blocks`` blocks."""
    if n < 3:
        raise ValueError("n must be at least three")
    if not (3 <= blocks <= n):
        raise ValueError("require 3 <= blocks <= n")
    q, r = divmod(n, blocks)
    lengths = np.asarray([q + 1] * r + [q] * (blocks - r), dtype=np.int64)
    if np.any(lengths <= 0):
        raise AssertionError("empty block")
    starts = np.zeros(blocks, dtype=np.int64)
    if blocks > 1:
        starts[1:] = np.cumsum(lengths[:-1])
    ends = starts + lengths
    if int(ends[-1]) != n:
        raise AssertionError("partition does not cover input")
    # This is the exact condition needed for beta to separate displacements.
    if 2 * (int(lengths.max()) - 1) >= n:
        raise ValueError("blocks too long for no-wrap displacement separation")
    return starts, lengths, ends


def _tri(t: int) -> int:
    return t * (t - 1) // 2


def local_phase(n: int, start: int, length: int, state: ChirpState) -> ComplexArray:
    state.validate(n)
    out = np.empty(length, dtype=np.complex128)
    h = n & 1
    for t in range(length):
        phase_n = (state.a * _tri(t) + (state.a * start + state.beta) * t) % n
        phase_2n = (2 * phase_n + h * t) % (2 * n)
        out[t] = np.exp(1j * np.pi * phase_2n / n)
    return out


def compress_blocks(
    x: npt.ArrayLike,
    blocks: int,
    state: ChirpState,
) -> tuple[ComplexArray, np.ndarray, np.ndarray, np.ndarray]:
    arr = np.asarray(x, dtype=np.complex128).reshape(-1)
    n = arr.size
    state.validate(n)
    starts, lengths, ends = balanced_partition(n, blocks)
    summaries = np.empty(blocks, dtype=np.complex128)
    for b, (start, length) in enumerate(zip(starts, lengths)):
        s = int(start)
        ell = int(length)
        summaries[b] = np.sum(local_phase(n, s, ell, state) * arr[s:s + ell])
    return summaries, starts, lengths, ends


def materialize_projected_signal(
    x: npt.ArrayLike,
    blocks: int,
    state: ChirpState,
) -> ComplexArray:
    arr = np.asarray(x, dtype=np.complex128).reshape(-1)
    summaries, starts, lengths, _ = compress_blocks(arr, blocks, state)
    out = np.empty(arr.size, dtype=np.complex128)
    for summary, start, length in zip(summaries, starts, lengths):
        s = int(start)
        ell = int(length)
        out[s:s + ell] = np.conj(local_phase(arr.size, s, ell, state)) * summary
    return out


def pairwise_sum(values: npt.ArrayLike, dtype: Any = np.complex128) -> complex:
    data = np.asarray(values, dtype=dtype).reshape(-1)
    if data.size == 0:
        return 0.0 + 0.0j
    size = 1 << (data.size - 1).bit_length()
    temp = np.zeros(size, dtype=dtype)
    temp[: data.size] = data
    width = size
    while width > 1:
        temp[: width // 2] = temp[:width:2] + temp[1:width:2]
        width //= 2
    return complex(temp[0])


def balanced_exclusive_scan(values: npt.ArrayLike, dtype: Any = np.complex128) -> np.ndarray:
    data = np.asarray(values, dtype=dtype).reshape(-1)
    n = data.size
    if n == 0:
        return np.empty(0, dtype=dtype)
    size = 1 << (n - 1).bit_length()
    temp = np.zeros(size, dtype=dtype)
    temp[:n] = data
    stride = 2
    while stride <= size:
        right = np.arange(stride - 1, size, stride)
        left = right - stride // 2
        temp[right] = temp[left] + temp[right]
        stride *= 2
    temp[-1] = 0.0 + 0.0j
    stride = size
    while stride >= 2:
        right = np.arange(stride - 1, size, stride)
        left = right - stride // 2
        saved = temp[left].copy()
        temp[left] = temp[right]
        temp[right] = temp[right] + saved
        stride //= 2
    return temp[:n].copy()


def fft_convolve(a: npt.ArrayLike, b: npt.ArrayLike) -> ComplexArray:
    aa = np.asarray(a, dtype=np.complex128).reshape(-1)
    bb = np.asarray(b, dtype=np.complex128).reshape(-1)
    if aa.size == 0 or bb.size == 0:
        return np.empty(0, dtype=np.complex128)
    need = aa.size + bb.size - 1
    size = 1 << (need - 1).bit_length()
    return np.fft.ifft(np.fft.fft(aa, size) * np.fft.fft(bb, size))[:need]


def recurrence_setup(nodes: npt.ArrayLike) -> tuple[ComplexArray, ComplexArray]:
    """Return q(z)=prod(1-lambda*z) and q^{-1} mod z^B.

    The prototype uses quadratic setup.  A subproduct tree and Newton power
    series inversion reduce this to quasi-linear setup; the theorem charges
    either implementation explicitly.
    """
    lam = np.asarray(nodes, dtype=np.complex128).reshape(-1)
    if lam.size == 0:
        raise ValueError("at least one node is required")
    q = np.asarray([1.0 + 0.0j])
    for z in lam:
        q = np.convolve(q, np.asarray([1.0 + 0.0j, -z]))
    b = lam.size
    inv = np.zeros(b, dtype=np.complex128)
    inv[0] = 1.0 / q[0]
    for n in range(1, b):
        total = 0.0 + 0.0j
        for j in range(1, min(n, b) + 1):
            total += q[j] * inv[n - j]
        inv[n] = -total / q[0]
    return q, inv


def exponential_sequences_recurrence(
    nodes: npt.ArrayLike,
    weights: npt.ArrayLike,
    length: int,
) -> np.ndarray:
    """Generate one or several exponential sums by blocked recurrence.

    ``weights`` has shape (channels,B) or (B,).  Channel c is
        s_c[k] = sum_b weights[c,b] * nodes[b]**k.

    Each B-term output block is obtained by one past-convolution and one
    multiplication by q^{-1} mod z^B.  This is exact in the algebraic model.
    """
    lam = np.asarray(nodes, dtype=np.complex128).reshape(-1)
    w = np.asarray(weights, dtype=np.complex128)
    single = w.ndim == 1
    if single:
        w = w[None, :]
    if w.ndim != 2 or w.shape[1] != lam.size:
        raise ValueError("weights must have B columns")
    if length < 0:
        raise ValueError("length must be nonnegative")
    channels, b = w.shape
    if length == 0:
        ans = np.empty((channels, 0), dtype=np.complex128)
        return ans[0] if single else ans
    initial = min(b, length)
    exponents = np.arange(initial, dtype=np.int64)[:, None]
    vandermonde = lam[None, :] ** exponents
    out = np.empty((channels, length), dtype=np.complex128)
    out[:, :initial] = w @ vandermonde.T
    if length <= b:
        return out[0] if single else out

    q, inv = recurrence_setup(lam)
    cursor = b
    while cursor < length:
        take = min(b, length - cursor)
        for c in range(channels):
            past = out[c, cursor - b: cursor]
            past_q = fft_convolve(past, q)
            rhs = -past_q[b: b + take]
            block = fft_convolve(rhs, inv)[:take]
            out[c, cursor: cursor + take] = block
        cursor += take
    return out[0] if single else out


def exponential_sequences_direct(
    nodes: npt.ArrayLike,
    weights: npt.ArrayLike,
    length: int,
) -> np.ndarray:
    lam = np.asarray(nodes, dtype=np.complex128).reshape(-1)
    w = np.asarray(weights, dtype=np.complex128)
    single = w.ndim == 1
    if single:
        w = w[None, :]
    exponents = np.arange(length, dtype=np.int64)[:, None]
    values = w @ (lam[None, :] ** exponents).T
    return values[0] if single else values


def boundary_weights(
    summaries: npt.ArrayLike,
    starts: npt.ArrayLike,
    lengths: npt.ArrayLike,
    n: int,
    state: ChirpState,
) -> ComplexArray:
    """Put end-boundary weights in the cyclic start-node order."""
    d = np.asarray(summaries, dtype=np.complex128).reshape(-1)
    starts_i = np.asarray(starts, dtype=np.int64).reshape(-1)
    lengths_i = np.asarray(lengths, dtype=np.int64).reshape(-1)
    if not (d.size == starts_i.size == lengths_i.size):
        raise ValueError("shape mismatch")
    h = n & 1
    end_weights = np.empty_like(d)
    for b, (summary, start, ell) in enumerate(zip(d, starts_i, lengths_i)):
        s = int(start)
        L = int(ell)
        phase_n = (-state.a * _tri(L) - state.a * s * L - state.beta * L) % n
        phase_2n = (2 * phase_n - h * L) % (2 * n)
        coeff = np.exp(1j * np.pi * phase_2n / n)
        end_weights[(b + 1) % d.size] = coeff * summary
    return end_weights


def forcing_sequences(
    summaries: npt.ArrayLike,
    starts: npt.ArrayLike,
    lengths: npt.ArrayLike,
    n: int,
    state: ChirpState,
    method: str = "recurrence",
) -> ComplexArray:
    d = np.asarray(summaries, dtype=np.complex128).reshape(-1)
    starts_i = np.asarray(starts, dtype=np.int64).reshape(-1)
    nodes = np.exp(-2j * np.pi * starts_i.astype(np.float64) / n)
    end_w = boundary_weights(d, starts_i, lengths, n, state)
    weights = np.vstack([d, end_w])
    if method == "recurrence":
        seq = exponential_sequences_recurrence(nodes, weights, n)
    elif method == "direct":
        seq = exponential_sequences_direct(nodes, weights, n)
    else:
        raise ValueError("method must be recurrence or direct")
    return (seq[0] - seq[1]) / math.sqrt(n)


def decode_projected_spectrum(
    summaries: npt.ArrayLike,
    starts: npt.ArrayLike,
    lengths: npt.ArrayLike,
    n: int,
    state: ChirpState,
    forcing_method: str = "recurrence",
    dtype: Any = np.complex128,
) -> np.ndarray:
    state.validate(n)
    forcing = forcing_sequences(summaries, starts, lengths, n, state, forcing_method)
    j = np.arange(n, dtype=np.int64)
    indices = (state.a * j) % n
    gauge = np.empty(n, dtype=np.complex128)
    h = n & 1
    for jj in range(n):
        phase_n = (state.a * _tri(jj) + state.beta * jj) % n
        phase_2n = (2 * phase_n + h * jj) % (2 * n)
        gauge[jj] = np.exp(1j * np.pi * phase_2n / n)
    terms = np.asarray(forcing[indices] / gauge, dtype=dtype)
    seed = pairwise_sum(terms, dtype) / 2.0
    prefix = balanced_exclusive_scan(terms, dtype)
    out = np.empty(n, dtype=dtype)
    out[indices] = np.asarray(gauge, dtype=dtype) * (seed - prefix)
    return out


def one_row_estimate(
    x: npt.ArrayLike,
    blocks: int,
    state: ChirpState,
    forcing_method: str = "recurrence",
    dtype: Any = np.complex128,
) -> np.ndarray:
    arr = np.asarray(x, dtype=np.complex128).reshape(-1)
    summaries, starts, lengths, _ = compress_blocks(arr, blocks, state)
    return decode_projected_spectrum(
        summaries, starts, lengths, arr.size, state, forcing_method, dtype
    )


def reference_row(x: npt.ArrayLike, blocks: int, state: ChirpState) -> ComplexArray:
    y = materialize_projected_signal(x, blocks, state)
    return np.fft.fft(y) / math.sqrt(y.size)
