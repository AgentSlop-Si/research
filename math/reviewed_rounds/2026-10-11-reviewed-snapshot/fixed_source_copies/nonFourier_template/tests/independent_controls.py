def hsh(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()

def near(v):
    lo, rem = divmod(v.numerator, v.denominator)
    return lo + int(2*rem >= v.denominator)

def two(e):
    return Q(1 << e) if e >= 0 else Q(1, 1 << -e)

def upper_binary(x):
    e = x.numerator.bit_length()-x.denominator.bit_length()
    return e + int(two(e) < x)

def norm(v):
    return sum((a*a+b*b for a,b in v), Q(0))

@lru_cache(None)
def integer_tensor(r):
    base = ((3,-4),(4,3))
    n = 1 << r
    a = []
    for i in range(n):
        row=[]
        for j in range(n):
            c=1
            for digit in range(r):
                c *= base[(i >> digit)&1][(j >> digit)&1]
            row.append(c)
        a.append(tuple(row))
    return tuple(a)

def mv(a, den, v):
    return [(sum((c*z[0] for c,z in zip(row,v)),Q(0))/den,
             sum((c*z[1] for c,z in zip(row,v)),Q(0))/den) for row in a]

def minus(a,b):
    return [(x[0]-y[0],x[1]-y[1]) for x,y in zip(a,b)]

def local(a, den, v, p, eta):
    size=len(v)
    largest=max(abs(c) for z in v for c in z)
    if not largest:
        return [(Q(0),Q(0)) for _ in v], Q(0)
    scale=two(upper_binary(largest)); unit=Q(1,1 << p)
    assert largest <= scale < 2*largest
    digits=[(near(z[0]/scale/unit),near(z[1]/scale/unit)) for z in v]
    assert all(abs(c) <= 1 << p for z in digits for c in z)
    # Assemble in a different order (interleaved real/imaginary) and decode.
    fields=[c+(1 << p) for z in digits for c in z]
    code=0
    for c in reversed(fields): code=code*(1 << (p+2))+c
    recovered=[]; rest=code
    for _ in fields:
        rest,c=divmod(rest,1 << (p+2)); recovered.append(c)
    assert recovered == fields and rest == 0
    sums=[(sum(c*z[0] for c,z in zip(row,digits)),
           sum(c*z[1] for c,z in zip(row,digits))) for row in a]
    zdigits=[(near(Q(x,den)),near(Q(y,den))) for x,y in sums]
    tableerr=sum((Q((x*den-u)**2+(y*den-w)**2,den*den) for (x,y),(u,w) in zip(zdigits,sums)),Q(0))*unit*unit
    assert tableerr <= Q(2*size,4)*unit*unit
    result=[(scale*unit*x,scale*unit*y) for x,y in zdigits]
    err=norm(minus(result,mv(a,den,v)))
    assert err <= eta*eta*norm(v)
    return result, err/(eta*eta*norm(v))

def run_circuit(d,k,t,vec,rounded=True):
    N=1 << d; L=(d+k-1)//k+1
    p=(1536*(1 << k)*L-1).bit_length()+t
    eta=Q(1,(1 << t)*8*L)
    v=list(vec); maxfrac=Q(0); calls=0; writes=0
    end=0
    for start in range(0,d,k):
        r=min(k,d-start); end=start+r
        delta=(5**end).bit_length()-(5**start).bit_length()
        a=integer_tensor(r); den=1 << delta
        visited=[]
        # Find each block by clearing the operated digits in every global index.
        mask=((1 << r)-1) << start
        bases=[i for i in range(N) if i & mask == 0]
        for base in bases:
            ix=[base | (b << start) for b in range(1 << r)]
            visited += ix
            value=[v[i] for i in ix]
            if rounded:
                out,ratio=local(a,den,value,p,eta)
                maxfrac=max(maxfrac,ratio); calls+=1
            else: out=mv(a,den,value)
            for i,z in zip(ix,out): v[i]=z; writes+=1
        assert sorted(visited) == list(range(N))
    a=((1 << ((5**d).bit_length()-1),),); den=5**d
    for i in range(N):
        if rounded:
            out,ratio=local(a,den,[v[i]],p,eta)
            calls+=1; maxfrac=max(maxfrac,ratio)
        else: out=mv(a,den,[v[i]])
        v[i]=out[0]; writes+=1
    assert writes == N*L
    return v, {'writes':writes,'local_calls':calls,'p':p,
               'max_local_budget_fraction':str(maxfrac)}

def budget(d,k,t):
    m=1 << k; L=(d+k-1)//k+1
    p=(1536*m*L-1).bit_length()+t; b=2*(p+2)
    return {'k':k,'m':m,'L':L,'p':p,'b':b,'E':2+m*b,'legal':2*(2+m*b)<=d}

def best(d,t):
    ans=[budget(d,k,t) for k in range(1,d.bit_length()) if budget(d,k,t)['legal']]
    return ans[-1] if ans else None

